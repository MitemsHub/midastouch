def test_the_reversal_direction_is_actually_reversed_in_the_rows() -> None:
    """A day that closed up must be traded SHORT and its gross must be the negative of the
    final move — the invariant that makes this a reversal study and not another momentum run."""
    art = _load(ART)
    for r in art["rows_primary"]:
        if r["r_rod"] > 0:
            assert r["side"] == "short"
        elif r["r_rod"] < 0:
            assert r["side"] == "long"
        # the R columns are the dollars divided by the declared stop, and the direction-signed
        # return agrees in sign with the direction-signed price move
        assert r["gross_r"] == pytest.approx(r["gross_usd"] / r["stop_usd"], abs=1e-9)
        assert r["cost_r"] == pytest.approx(r["cost_usd"] / r["stop_usd"], abs=1e-9)
        assert r["net_r"] == pytest.approx((r["gross_usd"] - r["cost_usd"]) / r["stop_usd"],
                                           abs=1e-9)
        assert (r["r_lh"] >= 0) == (r["gross_r"] >= 0)


