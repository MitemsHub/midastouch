# --- the structural guard: consumed days are never re-tested ------------------------------

def test_the_primary_sample_is_disjoint_from_the_consumed_days() -> None:
    """The whole point. If this ever fails, the study has become a second look at the same
    outcomes with the sign flipped, and its p-value means nothing."""
    art, mom = _load(ART), _load(MOMENTUM_ART)
    consumed = {r["day"] for r in mom["rows"]}
    primary = {r["day"] for r in art["rows_primary"]}
    auxiliary = {r["day"] for r in art["rows_auxiliary"]}
    assert primary and auxiliary
    assert not (primary & consumed), "primary sample re-tests consumed days"
    assert not (auxiliary & consumed), "auxiliary sample re-tests consumed days"
    assert not (primary & auxiliary)


def test_the_recorded_sample_counts_match_the_declared_selector() -> None:
    if not M15.is_file():
        pytest.skip("venue M15 series not present")
    import midas_sweep as ms
    import gold_intraday_momentum as gim
    art = _load(ART)
    days = gim.by_day(ms.load_bars(str(M15)))
    consumed = rev.consumed_days(str(MOMENTUM_ART))
    primary_days, aux_days = rev.samples(days, consumed)
    assert art["primary_sample_days"] == len(art["rows_primary"]) <= len(primary_days)
    assert art["consumed_days"] + art["unconsumed_days"] == len(days)
    # the selector's output is the declared rule's; rows can only be fewer (ATR/era refusals)
    assert set(r["day"] for r in art["rows_primary"]) <= set(primary_days)
    assert set(r["day"] for r in art["rows_auxiliary"]) <= set(aux_days)


