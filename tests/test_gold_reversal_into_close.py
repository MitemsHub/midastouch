# --- the artifact agrees with its own rule -----------------------------------------------

def test_the_recorded_primary_numbers_recompute_from_the_rows() -> None:
    art = _load(ART)
    rows = art["rows_primary"]
    n = len(rows)
    p = art["primary"]
    assert n == p["n"]
    mean = sum(r["net_r"] for r in rows) / n
    sd = math.sqrt(sum((r["net_r"] - mean) ** 2 for r in rows) / (n - 1))
    assert abs(mean - p["mean"]) < 5e-4
    assert abs(sd - p["sd"]) < 5e-4
    assert abs(p["mde"] - (1.96 + 0.8416) * sd / math.sqrt(n)) < 5e-4


