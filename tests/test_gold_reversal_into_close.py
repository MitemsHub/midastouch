"""The reversal study's declaration, its refusal to reuse consumed days, and its arithmetic.

WHY THIS FILE EXISTS. This study was built on a hypothesis generated by an *already measured*
window, which is the one situation where a programme like this can quietly fool itself: flip
the sign, re-test the same days, report a fresh-looking t-statistic. The guard is structural, so
it is pinned structurally — the primary sample must be disjoint from the days the momentum study
consumed, and that is asserted against the artifacts rather than trusted to the harness.

The second pin is the verdict: it must be the declared three-way rule applied to the numbers
recorded in the artifact, so neither the verdict nor the numbers can drift apart.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

import gold_reversal_into_close as rev  # noqa: E402

PROTOCOL = ROOT / "docs" / "GOLD_REVERSAL_INTO_CLOSE_PROTOCOL.md"
VERDICT = ROOT / "docs" / "GOLD_REVERSAL_INTO_CLOSE_VERDICT_20260921.md"
ART = ROOT / "artifacts" / "gold_reversal_into_close.json"
MOMENTUM_ART = ROOT / "artifacts" / "gold_intraday_momentum.json"
M15 = ROOT / "data" / "forex" / "xauusd" / "XAUUSD_M15_upcomers.csv"


def _load(p: Path) -> dict:
    if not p.is_file():
        pytest.skip(f"{p.name} not generated in this checkout")
    return json.loads(p.read_text(encoding="utf-8"))


